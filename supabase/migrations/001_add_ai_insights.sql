-- Create ai_insights table for persisting AI review results

CREATE TABLE IF NOT EXISTS public.ai_insights (
  insight_id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  user_id UUID NOT NULL,
  insight_date TIMESTAMP WITHOUT TIME ZONE NOT NULL,
  productivity_level DOUBLE PRECISION NULL,
  consistency_rate DOUBLE PRECISION NULL,
  cycles_total NUMERIC NOT NULL,
  peak_hours NUMERIC NOT NULL,
  peak_days TEXT[] NOT NULL,
  insight_message TEXT NULL,
  recommendation TEXT NULL,
  milestone TEXT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
  models_used JSON NULL,
  most_used_preset_timer BIGINT NULL,
  CONSTRAINT ai_insights_pkey PRIMARY KEY (insight_id),
  CONSTRAINT ai_insights_user_id_insight_date_key UNIQUE (user_id, insight_date),
  CONSTRAINT ai_insights_most_used_preset_timer_fkey FOREIGN KEY (most_used_preset_timer) REFERENCES timer_presets (preset_id) ON DELETE CASCADE,
  CONSTRAINT ai_insights_user_id_fkey FOREIGN KEY (user_id) REFERENCES auth.users (id) ON DELETE CASCADE
);

-- Index for fast latest-per-user lookups
CREATE INDEX IF NOT EXISTS idx_ai_insights_user_id_created_at
  ON public.ai_insights (user_id, created_at DESC);

-- Add ai_review_count column to daily_stats if not present
ALTER TABLE public.daily_stats
  ADD COLUMN IF NOT EXISTS ai_review_count INTEGER DEFAULT 0;

-- RLS: users can only see their own insights
ALTER TABLE public.ai_insights ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Users can view own insights"
  ON public.ai_insights
  FOR SELECT
  USING (auth.uid() = user_id);

CREATE POLICY "Users can insert own insights"
  ON public.ai_insights
  FOR INSERT
  WITH CHECK (auth.uid() = user_id);
