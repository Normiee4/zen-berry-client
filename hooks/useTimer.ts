import { useTimerStore } from "@/store/timer-store"

export function useTimer() {
  const {
    mode,
    timeLeft,
    isRunning,
    presets,
    activePresetId,
    toggle,
    reset,
    setMode,
    setPreset,
    addPreset,
    updatePreset,
    deletePreset,
    loadPresets,
    loadStats,
    completedFocusCycle,
    clearCompletedFocusCycle,
    completedBreakCycle,
    clearCompletedBreakCycle,
    showBreakReminder,
    restoreSession,
    currentStreak,
    pomodorosToday,
    alarmSound,
    setAlarmSound,
    consecutiveFocusSeconds,
    snoozedUntilSeconds,
    needsBreak,
    takeBreak,
    snoozeBreakReminder,
    resetConsecutiveFocus,
    completedMITTodayCount,
    incrementCompletedMIT,
    decrementCompletedMIT,
    setCompletedMITTodayCount,
  } = useTimerStore()

  return {
    // State
    mode,
    timeLeft,
    isRunning,
    presets,
    activePresetId,
    currentStreak,
    pomodorosToday,
    completedFocusCycle,
    completedBreakCycle,
    showBreakReminder,
    consecutiveFocusSeconds,
    snoozedUntilSeconds,
    needsBreak,
    completedMITTodayCount,
    // Computed (optional, but keeps component simple)
    activePreset: presets.find((p) => p.id === activePresetId) || presets[0],
    // Actions
    toggle,
    reset,
    setMode,
    setPreset,
    addPreset,
    updatePreset,
    deletePreset,
    loadPresets,
    loadStats,
    restoreSession,
    clearCompletedFocusCycle,
    clearCompletedBreakCycle,
    alarmSound,
    setAlarmSound,
    takeBreak,
    snoozeBreakReminder,
    resetConsecutiveFocus,
    incrementCompletedMIT,
    decrementCompletedMIT,
    setCompletedMITTodayCount,
  }
}